#include <stdio.h>

int main() {
    unsigned int reg = 0;

    // 操作 A：将第 3 位置 1
    // 原理：1 << 3 得到 00001000 (0x08)，按位或(|)可以把特定位置1且不影响其他位
    reg |= (1 << 3);
    printf("A: 第3位置1后: 0x%08X\n", reg);

    // 操作 B：将第 0 位和第 7 位同时置 1
    // 原理：构造掩码 10000001 (0x81)，按位或
    reg |= (1 << 0) | (1 << 7);
    printf("B: 第0和7位置1后: 0x%08X\n", reg);

    // 操作 C：将第 3 位清零
    // 原理：1 << 3 取反变成 11110111，按位与(&)可以强行抹掉那一位
    reg &= ~(1 << 3);
    printf("C: 第3位清零后: 0x%08X\n", reg);

    // 操作 D：将第 0 位翻转（0变1，1变0）
    // 原理：与1异或(^)会翻转，与0异或保持原样
    reg ^= (1 << 0);
    printf("D: 第0位翻转后: 0x%08X\n", reg);

    // 操作 E：判断第 7 位是不是 1
    // 原理：用掩码取出第7位。如果结果不等于0，说明原来是1
    if ((reg & (1 << 7)) != 0) {
        printf("E: 第7位是1\n");
    } else {
        printf("E: 第7位是0\n");
    }

    return 0;
}
